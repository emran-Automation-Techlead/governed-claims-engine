"""Per-advisory Pillow review: snapshot of public advisory records + rendered table.

Usage (from the project root):
  python scripts/pillow_advisory_review.py --check                 # table in the .md matches the snapshot? (offline, used by a test)
  python scripts/pillow_advisory_review.py --write                 # re-render the table into governance/PILLOW_ADVISORY_REVIEW.md
  python scripts/pillow_advisory_review.py --refresh AUDIT.json    # NETWORK: re-fetch OSV records for the Pillow ids in a
                                                                   # `pip-audit -f json` file, rewrite the snapshot, then --write

The snapshot (governance/pillow_advisories.json) stores what OSV (https://osv.dev, GitHub Advisory Database records) said on the
retrieval date: identifier, CVE alias, severity label, CVSS vector, affected range, summary. The classification columns
(vulnerable surface / what must happen to trigger it) are derived from the summary by the keyword rules below - a *triage aid*, not a
substitute for reading each advisory; the reachability conclusion is argued in the document's prose, not computed here.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / "governance" / "pillow_advisories.json"
DOC = ROOT / "governance" / "PILLOW_ADVISORY_REVIEW.md"
BEGIN, END = "<!-- BEGIN ADVISORY TABLE (generated by scripts/pillow_advisory_review.py) -->", "<!-- END ADVISORY TABLE -->"
SEV_RANK = {"CRITICAL": 0, "HIGH": 1, "MODERATE": 2, "MEDIUM": 2, "LOW": 3}

# (regex on lower-cased summary, vulnerable surface, what the application must do for it to matter)
RULES: list[tuple[str, str, str]] = [
    (r"ghostscript|\beps\b", "EPS / Ghostscript", "opens an EPS file from an untrusted source and a Ghostscript binary is installed"),
    (r"pdf|pdfparser", "PDF writer / PdfParser", "calls Image.save(format=\"PDF\"[, append=True]) or PdfParser on attacker-controlled PDF data"),
    (r"tiff|tiffdecode|_tiffwriteproc", "TIFF decode or encode", "opens an untrusted TIFF, or saves TIFF output derived from untrusted images"),
    (r"libopenjp2|jpeg ?2000|j2k", "bundled JPEG 2000 library", "opens an untrusted JPEG 2000 image"),
    (r"freetype|stroker|glyph", "font rendering", "draws text with attacker-influenced parameters"),
    (r"arrow export", "Arrow export", "exports images through the Arrow interface with PILLOW_ALIGNMENT > 1"),
    (r"transform|rank filter|imageexpand|imagemorph|_imagingmorph|image\.merge|imagingexpand|undefined behavior|integer operations",
     "image-processing API", "calls the affected Pillow function on attacker-influenced images or arguments"),
    (r"gif|apng|png|bmp|msp|xbm|mpo|dcx|spider|mic\b|fpx|flashpix|wmf|emf|tario|tar\b|jpeg|multi-frame|exif|decompression|raw decoder",
     "image-format decoder", "opens or loads an untrusted file of that format with Image.open()/load()"),
]


def classify(summary: str) -> tuple[str, str]:
    s = summary.lower()
    for rx, surface, prerequisite in RULES:
        if re.search(rx, s):
            return surface, prerequisite
    return "other", "see the advisory"


def _event(events: list[dict], key: str) -> str:
    return next((e[key] for e in events if key in e), "")


def to_row(rec: dict) -> dict:
    events = rec["affected"][0]["ranges"][0]["events"]
    cve = next((a for a in rec.get("aliases", []) if a.startswith("CVE-")), "")
    return {
        "id": rec["id"], "cve": cve, "severity": (rec.get("database_specific", {}) or {}).get("severity", "UNKNOWN"),
        "cvss": (rec.get("severity") or [{}])[0].get("score", ""), "introduced": _event(events, "introduced"),
        "fixed": _event(events, "fixed"), "published": (rec.get("published") or "")[:10],
        "summary": re.sub(r"\s+", " ", rec.get("summary") or re.sub(r"^Pillow is a Python imaging library\.\s*", "", rec.get("details", ""))[:220]).strip(),
    }


def refresh(audit_json: Path) -> None:
    audit = json.loads(audit_json.read_text("utf-8-sig"))
    dep = next(d for d in audit["dependencies"] if d["name"].lower() == "pillow")
    rows = []
    for v in dep["vulns"]:
        with urllib.request.urlopen(f"https://api.osv.dev/v1/vulns/{v['id']}", timeout=30) as r:
            rec = json.load(r)
        row = to_row(rec)
        if row["severity"] == "UNKNOWN":  # PYSEC-* records carry no label; take it from the GHSA alias record
            for alias in (a for a in rec.get("aliases", []) if a.startswith("GHSA-")):
                with urllib.request.urlopen(f"https://api.osv.dev/v1/vulns/{alias}", timeout=30) as r2:
                    row["severity"] = (json.load(r2).get("database_specific", {}) or {}).get("severity", "UNKNOWN")
                break
        rows.append(row)
    rows.sort(key=lambda r: (SEV_RANK.get(r["severity"], 9), r["id"]))
    SNAPSHOT.write_text(json.dumps({
        "source": "OSV (api.osv.dev) records for the Pillow ids reported by pip-audit",
        "retrieved_utc": datetime.now(UTC).strftime("%Y-%m-%d"), "pillow_version": dep["version"],
        "advisories": rows}, indent=2, ensure_ascii=False) + "\n", "utf-8")
    print(f"snapshot rewritten: {len(rows)} advisories")


def render(snapshot: dict) -> str:
    rows = snapshot["advisories"]
    counts: dict[str, int] = {}
    for r in rows:
        counts[r["severity"]] = counts.get(r["severity"], 0) + 1
    head = (f"Snapshot of {len(rows)} advisories for Pillow {snapshot['pillow_version']} retrieved {snapshot['retrieved_utc']} "
            f"({', '.join(f'{k} {v}' for k, v in sorted(counts.items(), key=lambda kv: SEV_RANK.get(kv[0], 9)))}). "
            "Every record's fixed version is shown; \"introduced 0\" means all versions.\n\n")
    lines = ["| # | Advisory | CVE (OSV alias) | Severity | CVSS vector | Affected range | Vulnerable surface | Must happen to trigger | Reachable here? |",
             "|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        surface, prereq = classify(r["summary"])
        rng = f"{r['introduced'] or '?'} -> {r['fixed'] or 'unfixed'}"
        lines.append(f"| {i} | [{r['id']}](https://github.com/advisories/{r['id']}) | {r['cve'] or '-'} | {r['severity']} | "
                     f"`{r['cvss']}` | {rng} | {surface}: {r['summary']} | {prereq} | **No** (see section 3) |")
    return head + "\n".join(lines) + "\n"


def table_in_doc() -> str:
    text = DOC.read_text("utf-8")
    return text.split(BEGIN, 1)[1].split(END, 1)[0].strip("\n") + "\n"


def write_doc() -> None:
    text = DOC.read_text("utf-8")
    pre, rest = text.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    DOC.write_text(pre + BEGIN + "\n" + render(json.loads(SNAPSHOT.read_text("utf-8"))) + END + post, "utf-8")
    print("table rewritten")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--refresh", type=Path, metavar="PIP_AUDIT_JSON")
    a = ap.parse_args(argv)
    if a.refresh:
        refresh(a.refresh)
        write_doc()
        return 0
    if a.write:
        write_doc()
        return 0
    if a.check:
        fresh = render(json.loads(SNAPSHOT.read_text("utf-8")))
        if fresh != table_in_doc():
            print("governance/PILLOW_ADVISORY_REVIEW.md is out of date: run --write")
            return 1
        print("up to date")
        return 0
    ap.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
