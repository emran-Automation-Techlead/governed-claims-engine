"""Generate requirements-container.txt: the Linux/CPython-3.11 dependency closure of requirements-demo.txt,
pinned to exact versions with the SHA-256 of EVERY published wheel of that version (like `pip-compile --generate-hashes`,
without adding a tool). Used with `pip install --require-hashes --only-binary=:all: --no-deps`.

Needs network (PyPI public metadata). Run from the project root:  python scripts/make_container_requirements.py
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLATFORMS = ["manylinux2014_x86_64", "manylinux_2_17_x86_64", "manylinux_2_27_x86_64", "manylinux_2_28_x86_64",
             "manylinux2014_aarch64", "manylinux_2_17_aarch64", "manylinux_2_28_aarch64"]


def resolve(requirements: Path) -> dict[str, str]:
    with tempfile.TemporaryDirectory() as tmp:
        cmd = [sys.executable, "-m", "pip", "download", "-q", "-r", str(requirements), "-d", tmp,
               "--only-binary=:all:", "--python-version", "3.11", "--implementation", "cp"]
        for p in PLATFORMS[:4]:
            cmd += ["--platform", p]
        subprocess.run(cmd, check=True)  # noqa: S603 - fixed argv built from sys.executable and constants
        out: dict[str, str] = {}
        for f in Path(tmp).glob("*.whl"):
            name, version = f.name.split("-")[:2]
            out[re.sub(r"[-_.]+", "-", name).lower()] = version
        return out


def wheel_hashes(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as r:
        data = json.load(r)
    return sorted({f["digests"]["sha256"] for f in data["urls"] if f["filename"].endswith(".whl")})


def main() -> None:
    pins = resolve(ROOT / "requirements-demo.txt")
    lines = ["# GENERATED by scripts/make_container_requirements.py - do not edit by hand.",
             "# Linux / CPython 3.11 closure of requirements-demo.txt; every wheel of each pinned version is hash-listed.",
             "# Install with: pip install --require-hashes --only-binary=:all: -r requirements-container.txt   (no --no-deps: fail loudly if a pin is missing)"]
    for name in sorted(pins):
        hashes = wheel_hashes(name, pins[name])
        if not hashes:
            raise SystemExit(f"no wheel hashes for {name}=={pins[name]}")
        lines.append(f"{name}=={pins[name]} \\")
        lines.append(" \\\n".join(f"    --hash=sha256:{h}" for h in hashes))
    (ROOT / "requirements-container.txt").write_text("\n".join(lines) + "\n", "utf-8")
    print(f"{len(pins)} packages pinned")


if __name__ == "__main__":
    main()